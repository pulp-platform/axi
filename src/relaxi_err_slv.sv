// AXI Error Slave: This module always responds with an AXI error for transactions that are sent to
// it.  This module optionally supports ATOPs if the `ATOPs` parameter is set.

module relaxi_err_slv #(
  parameter int unsigned          AxiIdWidth  = 0,                    // AXI ID Width
  parameter type                  axi_req_t   = logic,                // AXI 4 request struct, with atop field
  parameter type                  axi_resp_t  = logic,                // AXI 4 response struct
  parameter axi_pkg::resp_t       Resp        = axi_pkg::RESP_DECERR, // Error generated by this slave.
  parameter int unsigned          RespWidth   = 32'd64,               // Data response width, gets zero extended or truncated to r.data.
  parameter logic [RespWidth-1:0] RespData    = 64'hCA11AB1EBADCAB1E, // Hexvalue for data return value
  parameter bit                   ATOPs       = 1'b1,                 // Activate support for ATOPs.  Set to 1 if this slave could ever get an atomic AXI transaction.
  parameter int unsigned          MaxTrans    = 1                     // Maximum # of accepted transactions before stalling
) (
  input  logic      clk_i,   // Clock
  input  logic      rst_ni,  // Asynchronous reset active low
  input  logic      test_i,  // Testmode enable
  // slave port
  input  axi_req_t  slv_req_i,
  output axi_resp_t slv_resp_o,
  output logic [1:0] fault_o
);

  localparam int unsigned IdEccWidth    = AxiIdWidth + hsiao_ecc_pkg::min_ecc(AxiIdWidth);
  localparam int unsigned RDataWidth    = AxiIdWidth + $bits(axi_pkg::len_t);
  localparam int unsigned RDataEccWidth = RDataWidth + hsiao_ecc_pkg::min_ecc(RDataWidth);

  typedef logic [AxiIdWidth-1:0] id_t;
  typedef struct packed {
    id_t           id;
    axi_pkg::len_t len;
  } r_data_t;

  axi_req_t   err_req;
  axi_resp_t  err_resp;

  if (ATOPs) begin
    axi_atop_filter #(
      .AxiIdWidth       ( AxiIdWidth  ),
      .AxiMaxWriteTxns  ( MaxTrans    ),
      .axi_req_t        ( axi_req_t   ),
      .axi_resp_t       ( axi_resp_t  )
    ) i_atop_filter (
      .clk_i,
      .rst_ni,
      .slv_req_i  ( slv_req_i   ),
      .slv_resp_o ( slv_resp_o  ),
      .mst_req_o  ( err_req     ),
      .mst_resp_i ( err_resp    )
    );
  end else begin
    assign err_req    = slv_req_i;
    assign slv_resp_o = err_resp;
  end

  // w fifo
  logic    [2:0] w_fifo_full, w_fifo_empty;
  logic    [2:0] w_fifo_push, w_fifo_pop;
  id_t     w_fifo_data;
  // b fifo
  logic    [2:0] b_fifo_full, b_fifo_empty;
  logic    [2:0] b_fifo_push, b_fifo_pop;
  id_t     b_fifo_data;
  // r fifo
  logic    [2:0] r_fifo_full, r_fifo_empty;
  logic    [2:0] r_fifo_push, r_fifo_pop;

  r_data_t r_fifo_inp;
  r_data_t r_fifo_data;

  // r counter
  logic    [2:0] r_cnt_clear, r_cnt_en, r_cnt_load;
  logic    [2:0][$bits(axi_pkg::len_t)-1:0] r_current_beat;
  // r status
  logic    [2:0] r_busy_d, r_busy_q, r_busy_load;

  logic [4:0] err_slv_faults;   // 3 fifos + r_counter + r_busy voters

  // Intermediates: avoid bit-select into struct fields (Questa vopt-13198).
  logic [2:0] aw_valid_d, aw_ready_d;
  logic [2:0] w_valid_d,  w_ready_d, w_last_d;
  logic [2:0] b_valid_d,  b_ready_d;
  logic [2:0] ar_valid_d, ar_ready_d;
  logic [2:0] r_valid_d,  r_ready_d, r_last_d;

  assign aw_valid_d        = err_req.aw_valid;
  assign err_resp.aw_ready = aw_ready_d;
  assign w_valid_d         = err_req.w_valid;
  assign w_last_d          = err_req.w.last;
  assign err_resp.w_ready  = w_ready_d;
  assign b_ready_d         = err_req.b_ready;
  assign err_resp.b_valid  = b_valid_d;
  assign ar_valid_d        = err_req.ar_valid;
  assign err_resp.ar_ready = ar_ready_d;
  assign r_ready_d         = err_req.r_ready;
  assign err_resp.r_valid  = r_valid_d;

  logic [2:0]      r_busy_voted;
  logic [2:0][1:0] alt_r_busy;
  logic [2:0]      r_busy_faults;

  for (genvar i = 0; i < 3; i++) begin : gen_r_busy_alt
    for (genvar j = 0; j < 2; j++) begin : gen_alt
      assign alt_r_busy[i][j] = r_busy_q[(i+j+1) % 3];
    end
  end

  for (genvar i = 0; i < 3; i++) begin : gen_r_busy_vote
    TMR_voter_fail #(.VoterType(1)) i_r_busy_vote (
      .a_i              ( r_busy_q[i]      ),
      .b_i              ( alt_r_busy[i][0] ),
      .c_i              ( alt_r_busy[i][1] ),
      .majority_o       ( r_busy_voted[i]  ),
      .fault_detected_o ( r_busy_faults[i] )
    );
  end

  assign err_slv_faults[4] = |r_busy_faults;
  //--------------------------------------
  // Write Transactions
  //--------------------------------------
  // push, when there is room in the fifo
  for (genvar i = 0; i < 3; i++) begin : gen_aw_channel_tmr
    assign w_fifo_push[i] = aw_valid_d[i] & ~w_fifo_full[i];
    assign aw_ready_d[i]  = ~w_fifo_full[i];
  end

  rel_fifo #(
      .Depth       ( MaxTrans                           ),
      .FallThrough ( 1'b1                               ), // w fifo fall thru enabled so that w can eat beats if b is not sent
      .DataWidth   ( $bits(id_t)                        ),
      .TmrStatus   ( 1'b1                               ),
      .DataHasEcc  ( 1'b1                               )
  ) i_w_fifo (
      .clk_i,
      .rst_ni,
      .testmode_i( test_i                         ),
      .flush_i   ( '0                             ),
      .full_o    ( w_fifo_full                    ),
      .empty_o   ( w_fifo_empty                   ),
      .usage_o   (),
      .data_i    ( err_req.aw.id                  ), // w_fifo_inp
      .push_i    ( w_fifo_push                    ), // w_fifo_push
      .data_o    ( w_fifo_data                    ), // w_fifo_data this is also id type
      .pop_i     ( w_fifo_pop                     ),
      .fault_o   ( err_slv_faults[0]              )
    );

  for (genvar i = 0; i < 3; i++) begin : gen_w_channel_tmr
    always_comb begin : proc_w_channel
      w_ready_d[i]   = 1'b0;
      w_fifo_pop[i]  = 1'b0;
      b_fifo_push[i] = 1'b0;
      if (!w_fifo_empty[i] && !b_fifo_full[i]) begin
        // eat the beats
        w_ready_d[i] = 1'b1;
        // on the last w transaction
        if (w_valid_d[i] && w_last_d[i]) begin
          w_fifo_pop[i]  = 1'b1;
          b_fifo_push[i] = 1'b1;
        end
      end
    end
  end

  rel_fifo #(
      .Depth       ( unsigned'(2)                       ), // two placed so taht w can ear beats if b is not sent
      .FallThrough ( 1'b0                               ),
      .DataWidth   ( $bits(id_t)                        ),
      .TmrStatus   ( 1'b1                               ),
      .DataHasEcc  ( 1'b1                               )
  ) i_b_fifo (
      .clk_i,
      .rst_ni,
      .testmode_i( test_i                         ),
      .flush_i   ( '0                             ),
      .full_o    ( b_fifo_full                    ),
      .empty_o   ( b_fifo_empty                   ),
      .usage_o   (),
      .data_i    ( w_fifo_data                    ), // b_fifo_inp
      .push_i    ( b_fifo_push                    ), // b_fifo_push
      .data_o    ( b_fifo_data                    ), // b_fifo_data
      .pop_i     ( b_fifo_pop                     ),
      .fault_o   ( err_slv_faults[1]              )
    );

  // B channel data fields — single driver (same value for all replicas).
  always_comb begin : proc_b_data
    err_resp.b      = '0;
    err_resp.b.id   = b_fifo_data;
    err_resp.b.resp = Resp;
  end

  for (genvar i = 0; i < 3; i++) begin : gen_b_channel_tmr
    always_comb begin : proc_b_channel
      b_fifo_pop[i] = 1'b0;
      b_valid_d[i]  = 1'b0;
      if (!b_fifo_empty[i]) begin
        b_valid_d[i]  = 1'b1;
        b_fifo_pop[i] = b_ready_d[i];
      end
    end
  end

  //--------------------------------------
  // Read Transactions
  //--------------------------------------
  // push if there is room in the fifo
  for (genvar i = 0; i < 3; i++) begin : gen_ar_channel_tmr
    assign r_fifo_push[i] = ar_valid_d[i] & ~r_fifo_full[i];
    assign ar_ready_d[i]  = ~r_fifo_full[i];
  end

  assign r_fifo_inp.id  = err_req.ar.id;
  assign r_fifo_inp.len = err_req.ar.len;

  rel_fifo #(
      .Depth       ( MaxTrans                           ),
      .FallThrough ( 1'b0                               ),
      .DataWidth   ( $bits(r_data_t)                    ),
      .TmrStatus   ( 1'b1                               ),
      .DataHasEcc  ( 1'b1                               )
  ) i_r_fifo (
      .clk_i,
      .rst_ni,
      .testmode_i( test_i                         ),
      .flush_i   ( '0                             ),
      .full_o    ( r_fifo_full                    ),
      .empty_o   ( r_fifo_empty                   ),
      .usage_o   (),
      .data_i    ( r_fifo_inp                     ), // r_fifo_inp
      .push_i    ( r_fifo_push                    ), // r_fifo_push
      .data_o    ( r_fifo_data                    ), // r_fifo_data
      .pop_i     ( r_fifo_pop                     ),
      .fault_o   ( err_slv_faults[2]              )
    );

  // R channel data fields — single driver (same value for all replicas).
  always_comb begin : proc_r_data
    err_resp.r        = '0;
    err_resp.r.id     = r_fifo_data.id;
    err_resp.r.data   = RespData;
    err_resp.r.resp   = Resp;
    err_resp.r.last   = r_last_d;
  end

  for (genvar i = 0; i < 3; i++) begin : gen_r_channel_tmr
    always_comb begin : proc_r_channel
      // default assignments
      r_busy_d[i]    = r_busy_voted[i];
      r_busy_load[i] = 1'b0;
      // r fifo signals
      r_fifo_pop[i]  = 1'b0;
      // r counter signals
      r_cnt_clear[i] = 1'b0;
      r_cnt_en[i]    = 1'b0;
      r_cnt_load[i]  = 1'b0;
      // r channel handshakes
      r_valid_d[i]   = 1'b0;
      r_last_d[i]    = 1'b0;
      // control
      if (r_busy_voted[i]) begin
        r_valid_d[i] = 1'b1;
        r_last_d[i]  = (r_current_beat[i] == '0);
        // r transaction
        if (r_ready_d[i]) begin
          r_cnt_en[i] = 1'b1;
          if (r_current_beat[i] == '0) begin
            r_busy_d[i]    = 1'b0;
            r_busy_load[i] = 1'b1;
            r_cnt_clear[i] = 1'b1;
            r_fifo_pop[i]  = 1'b1;
          end
        end
      end else begin
        // when not busy and fifo not empty, start counter err gen
        if (!r_fifo_empty[i]) begin
          r_busy_d[i]    = 1'b1;
          r_busy_load[i] = 1'b1;
          r_cnt_load[i]  = 1'b1;
        end
      end
    end
  end

  for (genvar i = 0; i < 3; i++) begin : gen_r_busy_tmr
    always_ff @(posedge clk_i, negedge rst_ni) begin
      if (!rst_ni)             r_busy_q[i] <= '0;
      else if (r_busy_load[i]) r_busy_q[i] <= r_busy_d[i];
      else                     r_busy_q[i] <= r_busy_voted[i];
    end
  end

  rel_counter #(
    .WIDTH     ($bits(axi_pkg::len_t)),
    .STICKY_OVERFLOW ( 1'b0         ),
    .TmrStatus ( 1'b1               )
  ) i_r_counter (
    .clk_i     ( clk_i           ),
    .rst_ni    ( rst_ni          ),
    .clear_i   ( r_cnt_clear     ),
    .en_i      ( r_cnt_en        ),
    .load_i    ( r_cnt_load      ),
    .down_i    ( 3'b111          ),
    .d_i       ( r_fifo_data.len ),
    .q_o       ( r_current_beat  ),
    .overflow_o(                 ),
    .fault_o   ( err_slv_faults[3] )
  );

  assign fault_o[0] = |err_slv_faults;
  assign fault_o[1] = 1'b0;

  // pragma translate_off
  `ifndef VERILATOR
  initial begin
    assert (Resp == axi_pkg::RESP_DECERR || Resp == axi_pkg::RESP_SLVERR) else
      $fatal(1, "This module may only generate RESP_DECERR or RESP_SLVERR responses!");
  end
  `ifndef XSIM
  default disable iff (!rst_ni);
  if (!ATOPs) begin : gen_assert_atops_unsupported
    assume property( @(posedge clk_i) (slv_req_i.aw_valid |-> slv_req_i.aw.atop == '0)) else
     $fatal(1, "Got ATOP but not configured to support ATOPs!");
  end
  `endif
  `endif
  // pragma translate_on

endmodule
